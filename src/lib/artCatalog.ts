export function normalizeCategory(category: string | null | undefined): MajorCategory | 'all' {
  if (!category || category === 'all') return 'all';
  const c = category.toLowerCase().trim();
  if (c === 'wall-art' || c === 'paintings' || c === 'prints') return 'wall-art';
  if (c === 'sculptures' || c === 'figures') return 'sculptures';
  if (c === 'decorative-pieces' || c === 'objects' || c === 'decor') return 'decorative-pieces';
  return 'all';
}

export function getArtworkCategory(artwork: ArtworkProduct): MajorCategory {
  const cat = (artwork.category as string).toLowerCase();
  if (cat === 'wall-art' || cat === 'paintings' || cat === 'prints') return 'wall-art';
  if (cat === 'sculptures' || cat === 'figures') return 'sculptures';
  return 'decorative-pieces';
}

export function getCategoryLabel(category: string | null | undefined): string {
  const norm = normalizeCategory(category);
  switch (norm) {
    case 'wall-art':
      return 'Wall Art';
    case 'sculptures':
      return 'Sculptures';
    case 'decorative-pieces':
      return 'Decorative Pieces';
    default:
      return 'All Creations';
  }
}

export function getArtworksByCategory(category: string): ArtworkProduct[] {
  if (!category || category === 'all') return ARTWORKS;
  const norm = normalizeCategory(category);
  return ARTWORKS.filter((a) => getArtworkCategory(a) === norm);
}

